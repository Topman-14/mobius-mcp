#!/usr/bin/env node
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const skillsDir = join(here, "..", "..", "..", "skills");
const outFile = join(here, "..", "src", "skillPrompts.ts");

function parseFrontmatter(source, file) {
  const match = /^---\n([\s\S]*?)\n---\n?/.exec(source);
  if (!match) throw new Error(`${file}: missing YAML frontmatter`);

  const fields = {};
  let key;
  for (const line of match[1].split("\n")) {
    const start = /^([a-zA-Z_-]+):\s*(.*)$/.exec(line);
    if (start) {
      key = start[1];
      fields[key] = start[2].trim();
    } else if (key && line.trim()) {
      fields[key] += ` ${line.trim()}`;
    }
  }

  for (const required of ["name", "description"]) {
    if (!fields[required]) throw new Error(`${file}: frontmatter is missing "${required}"`);
  }
  return { fields, body: source.slice(match[0].length).trim() };
}

const entries = await readdir(skillsDir, { withFileTypes: true });
const prompts = [];

for (const entry of entries.filter((e) => e.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
  const file = join(skillsDir, entry.name, "SKILL.md");
  const source = await readFile(file, "utf8").catch(() => null);
  if (source === null) throw new Error(`${entry.name}: no SKILL.md`);
  const { fields, body } = parseFrontmatter(source, file);
  prompts.push({ name: fields.name, description: fields.description, body });
}

if (prompts.length === 0) throw new Error(`No skills found in ${skillsDir}`);

const generated = `// Generated by scripts/build-skill-prompts.mjs from skills/*/SKILL.md — do not edit.
export interface SkillPrompt {
  name: string;
  description: string;
  body: string;
}

export const SKILL_PROMPTS: SkillPrompt[] = ${JSON.stringify(prompts, null, 2)};
`;

await writeFile(outFile, generated);
console.log(`[build-skill-prompts] wrote ${prompts.length} skills to src/skillPrompts.ts`);
